"""Write the synthetic daily bars used by the backtest tests and the CLI smoke test.

The bars are generated, not real market data: a seeded random walk with drift and volatility
clusters on the real NYSE calendar. They exist only to exercise the code. Run from the
repository root:

    uv run python scripts/make_synthetic_bars.py
"""

import random
from datetime import date
from decimal import Decimal
from pathlib import Path

from aitrader.clock import TradingCalendar

OUT = Path("tests/fixtures/bars")
START, END = date(2023, 1, 3), date(2024, 12, 31)
SERIES = {
    # symbol: (seed, first close, daily drift, daily volatility, average volume)
    "SPY": (11, 385.0, 0.0006, 0.010, 70_000_000),
    "QQQ": (23, 270.0, 0.0008, 0.013, 45_000_000),
    "IWM": (37, 175.0, 0.0003, 0.015, 30_000_000),
}
CENT = Decimal("0.01")


def money(value: float) -> str:
    return str(Decimal(repr(value)).quantize(CENT))


def main() -> None:
    sessions = TradingCalendar().sessions(START, END)
    OUT.mkdir(parents=True, exist_ok=True)
    for symbol, (seed, first, drift, vol, volume) in SERIES.items():
        rng = random.Random(seed)  # noqa: S311 - reproducible test data, not security
        close = first
        regime = 1.0
        lines = ["date,open,high,low,close,volume"]
        for session in sessions:
            if rng.random() < 0.02:
                regime = rng.choice([0.7, 1.0, 1.6])
            gap = rng.gauss(0, vol * regime * 0.3)
            ret = rng.gauss(drift, vol * regime)
            open_ = close * (1 + gap)
            new_close = open_ * (1 + ret)
            high = max(open_, new_close) * (1 + abs(rng.gauss(0, vol * 0.4)))
            low = min(open_, new_close) * (1 - abs(rng.gauss(0, vol * 0.4)))
            shares = int(volume * (0.6 + 0.8 * rng.random()))
            lines.append(
                f"{session.isoformat()},{money(open_)},{money(high)},{money(low)},"
                f"{money(new_close)},{shares}"
            )
            close = float(money(new_close))
        (OUT / f"{symbol}.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (OUT / "README.md").write_text(
        "# Synthetic daily bars\n\n"
        "Generated by `scripts/make_synthetic_bars.py` (seeded random walk on the NYSE "
        "calendar). **Not real market data.** Used only by tests and the CLI smoke test.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
